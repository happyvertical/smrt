/**
 * Tests for the vitePluginAgentRoutes Vite plugin helpers.
 *
 * These test the pure generation functions without requiring
 * a full Vite build context.
 */

import { describe, expect, it } from 'vitest';
import {
  generatePageServerTs,
  generatePageSvelte,
  isValidRoutePath,
  routePathToDir,
} from './vite-plugin.js';

describe('vitePluginAgentRoutes', () => {
  describe('generatePageSvelte', () => {
    it('should generate a valid Svelte page wrapper', () => {
      const result = generatePageSvelte(
        '@happyvertical/praeco',
        'admin',
        'SourcesPanel',
      );

      expect(result).toContain('// AUTO-GENERATED by vitePluginAgentRoutes');
      expect(result).toContain(
        "import { SourcesPanel } from '@happyvertical/praeco/admin';",
      );
      expect(result).toContain('let { data } = $props();');
      expect(result).toContain('<SourcesPanel {...data} />');
    });

    it('should use custom admin export path', () => {
      const result = generatePageSvelte(
        '@happyvertical/caelus',
        'town',
        'ForecastPanel',
      );

      expect(result).toContain(
        "import { ForecastPanel } from '@happyvertical/caelus/town';",
      );
    });
  });

  describe('generatePageServerTs', () => {
    it('should generate a valid server load wrapper', () => {
      const result = generatePageServerTs(
        '@happyvertical/praeco',
        'admin',
        'loadSources',
      );

      expect(result).toContain('// AUTO-GENERATED by vitePluginAgentRoutes');
      expect(result).toContain(
        "import { loadSources } from '@happyvertical/praeco/admin';",
      );
      expect(result).toContain(
        "import type { PageServerLoad } from './$types';",
      );
      expect(result).toContain(
        'export const load: PageServerLoad = async (event)',
      );
      expect(result).toContain('params: event.params');
      expect(result).toContain('parent: event.parent');
      expect(result).toContain('fetch: event.fetch');
      expect(result).toContain('url: event.url');
    });

    it('should use the correct load function name', () => {
      const result = generatePageServerTs(
        '@happyvertical/praeco',
        'admin',
        'loadSourceDetail',
      );

      expect(result).toContain('import { loadSourceDetail }');
      expect(result).toContain('return loadSourceDetail({');
    });
  });

  describe('routePathToDir', () => {
    it('should wrap route path in a route group', () => {
      expect(routePathToDir('praeco', 'sources')).toBe('(praeco)/sources');
    });

    it('should handle nested paths', () => {
      expect(routePathToDir('praeco', 'sources/[sourceId]')).toBe(
        '(praeco)/sources/[sourceId]',
      );
    });

    it('should handle deeply nested paths', () => {
      expect(routePathToDir('praeco', 'sources/[sourceId]/edit')).toBe(
        '(praeco)/sources/[sourceId]/edit',
      );
    });
  });

  describe('isValidRoutePath', () => {
    it('should accept valid route paths', () => {
      expect(isValidRoutePath('sources')).toBe(true);
      expect(isValidRoutePath('sources/[sourceId]')).toBe(true);
      expect(isValidRoutePath('sources/[sourceId]/edit')).toBe(true);
      expect(isValidRoutePath('reports')).toBe(true);
    });

    it('should reject path traversal attempts', () => {
      expect(isValidRoutePath('../etc/passwd')).toBe(false);
      expect(isValidRoutePath('sources/../../etc')).toBe(false);
      expect(isValidRoutePath('..')).toBe(false);
    });

    it('should reject absolute paths', () => {
      expect(isValidRoutePath('/etc/passwd')).toBe(false);
      expect(isValidRoutePath('/sources')).toBe(false);
    });

    it('should reject empty or whitespace paths', () => {
      expect(isValidRoutePath('')).toBe(false);
      expect(isValidRoutePath('   ')).toBe(false);
    });

    it('should reject backslashes', () => {
      expect(isValidRoutePath('sources\\edit')).toBe(false);
    });

    it('should reject null bytes', () => {
      expect(isValidRoutePath('sources\0evil')).toBe(false);
    });
  });
});
