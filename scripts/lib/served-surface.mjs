/**
 * Served-surface gate: what each package serves on REST, MCP and CLI, as a
 * reviewable, committed snapshot (`served-surface/<package>.txt`).
 *
 * For each package P with a built manifest, one child process
 * (`served-surface-worker.mjs`) registers P's manifest and its transitive
 * `smrtDependencies` closure T through the public
 * `ObjectRegistry.registerPackageManifest`, and reads the served operations
 * from the transports' own decisions: the MCP tools `MCPGenerator` emits,
 * the commands `CLIGenerator.listCommands()` lists, and the shared REST
 * resolvers. P's file lists only P's keys (the served set); T is there for
 * ancestry, items and replacement only (the resolution set). A dependency
 * key that one of P's classes replaces is listed under `shadow` lines.
 *
 * Not modelled (stated in each file's header): the REST tenant-context
 * guard, runtime replacements (`registerRuntimeModel` `replaces`,
 * `registerOverride`), compositions of two or more dependents, and anything
 * registered only at run time. Freshness is the turbo-keyed `build` task:
 * locally the entry runs `turbo build` first; `--no-build` is for CI only,
 * where the step runs right after `pnpm run build` in the same job.
 */
