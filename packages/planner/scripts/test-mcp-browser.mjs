import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';
import { chromium } from 'playwright-core';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const chrome = ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium'].find(existsSync);
if (!chrome) throw Error('Chrome/Chromium is required for the MCP browser test');
const browser = await chromium.launch({headless:true,executablePath:chrome});
const page=await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(() => {
  localStorage.setItem('smrt-theme', JSON.stringify({preset:'studio',colorScheme:'dark'}));
  const listeners=[];
  const empty={ $schema:'https://s-m-r-t.dev/schemas/cookbook/v1.json',version:1,name:'Kitchen QA',recipes:[],features:[],policies:[] };
  const result=(revision,cookbook)=>({planId:'plan-12345678',state:{snapshot:{revision},cookbook}});
  let current=result(1,empty);
  window.__emitKitchen=(revision,name)=>{current=result(revision,{...empty,name});for(const listener of listeners)listener(current);};
  window.__calls=[];
  window.smrtKitchen={subscribe(listener){listeners.push(listener);setTimeout(()=>listener(current),0);return()=>{};},async callTool(name,args){
    if(name==='get_plan')return current;
    if(name!=='run_commands')throw Error('Unexpected tool '+name);
    window.__calls.push(args);
    if(window.__calls.length===1)throw Error('connection lost');
    if(window.__calls.length===2){current={ok:true,...result(3,args.commands[0].input.document)};return current;}
    current={ok:false,error:{code:'conflict',message:'Revision changed.'},...result(4,{...empty,name:'Other edit'})};return current;
  }};
});
await page.goto(pathToFileURL(resolve(root, 'app/mcp.html')).href);
await page.getByText('Kitchen QA',{exact:false}).first().waitFor({timeout:15000});
await page.waitForTimeout(250);
if((await page.evaluate(()=>window.__calls.length))!==0)throw Error('a stored browser theme changed the Kitchen plan on mount');
await page.evaluate(()=>window.__emitKitchen(2,'Kitchen QA updated'));
await page.getByText('Kitchen QA updated',{exact:false}).first().waitFor({timeout:15000});
await page.getByRole('tab',{name:'Settings'}).click();
await page.getByRole('textbox',{name:'Brand colour hex'}).fill('#c2410c');
await page.getByRole('button',{name:'Retry same edit'}).waitFor({timeout:15000});
await page.getByRole('button',{name:'Retry same edit'}).click();
await page.waitForFunction(()=>window.__calls.length===2);
const first=await page.evaluate(()=>window.__calls.slice(0,2));
if(first[0].id!==first[1].id || first[0].expectedRevision!==2)throw Error('retry changed batch id or revision');
await page.getByRole('textbox',{name:'Brand colour hex'}).fill('#0f766e');
await page.getByText('Revision changed.',{exact:false}).first().waitFor({timeout:15000});
const calls=await page.evaluate(()=>window.__calls);
if(calls.length!==3 || calls[2].expectedRevision!==3)throw Error('conflict command revision was wrong');
const draft=await page.locator('textarea[aria-label="Preserved cookbook edit"]').inputValue();
if(!draft.includes('#0f766e'))throw Error('conflicting draft was not preserved');
if(!(await page.getByRole('textbox',{name:'Brand colour hex'}).isDisabled()))throw Error('edits stayed enabled while a rejected draft was unacknowledged');
if((await page.locator('textarea[aria-label="Preserved cookbook edit"]').inputValue())!==draft)throw Error('rejected draft changed before dismissal');
await page.getByRole('button',{name:'Dismiss preserved edit'}).click();
await page.getByRole('textbox',{name:'Brand colour hex'}).fill('#713f12');
await page.waitForFunction(()=>window.__calls.length===4);
const second=await page.locator('textarea[aria-label="Preserved cookbook edit"]').inputValue();
if(!second.includes('#713f12'))throw Error('a second rejected draft was not preserved');
const recovering = await browser.newPage();
recovering.on('pageerror',e=>errors.push(e.message));
await recovering.addInitScript(() => {
  const empty={ $schema:'https://s-m-r-t.dev/schemas/cookbook/v1.json',version:1,name:'Recovered',recipes:[],features:[],policies:[] };
  const invalid={planId:'plan-12345678',state:{snapshot:{revision:1},cookbook:{...empty,theme:{preset:'unknown'}}}};
  const valid={planId:'plan-12345678',state:{snapshot:{revision:2},cookbook:empty}};
  window.smrtKitchen={subscribe(listener){setTimeout(()=>listener(invalid),0);return()=>{};},async callTool(name){if(name==='get_plan')return valid;throw Error('Unexpected tool '+name);}};
});
await recovering.goto(pathToFileURL(resolve(root, 'app/mcp.html')).href);
await recovering.getByRole('alert').waitFor({timeout:10000});
await recovering.getByText('Recovered',{exact:false}).first().waitFor({timeout:10000});
const themed = await browser.newPage();
themed.on('pageerror',e=>errors.push(e.message));
await themed.addInitScript(() => {
  localStorage.setItem('smrt-theme', JSON.stringify({preset:'studio',colorScheme:'dark'}));
  const empty={ $schema:'https://s-m-r-t.dev/schemas/cookbook/v1.json',version:1,name:'Themed',recipes:[],features:[],policies:[] };
  let current={planId:'plan-12345678',state:{snapshot:{revision:1},cookbook:empty}};
  window.__calls=[];
  window.smrtKitchen={subscribe(listener){setTimeout(()=>listener(current),0);return()=>{};},async callTool(name,args){
    if(name==='get_plan')return current;
    if(name!=='run_commands')throw Error('Unexpected tool '+name);
    window.__calls.push(args);
    current={ok:true,planId:'plan-12345678',state:{snapshot:{revision:current.state.snapshot.revision+1},cookbook:args.commands[0].input.document}};
    return current;
  }};
});
await themed.goto(pathToFileURL(resolve(root, 'app/mcp.html')).href);
await themed.getByText('Themed',{exact:false}).first().waitFor({timeout:15000});
await themed.getByRole('tab',{name:'Settings'}).click();
const presetSelect=themed.locator('select.smrt-theme-switcher__select');
await themed.waitForFunction(()=>document.querySelector('select.smrt-theme-switcher__select')?.value==='smrt',undefined,{timeout:10000});
if((await themed.evaluate(()=>window.__calls.length))!==0)throw Error('a stored browser theme changed the Kitchen plan');
await presetSelect.selectOption('happyvertical');
await themed.waitForFunction(()=>window.__calls.some(c=>c.commands[0].input.document.theme?.preset==='happyvertical'),undefined,{timeout:10000});
console.log(JSON.stringify({mounted:true,toolDrivenRefresh:true,retrySameId:true,conflictDraftPreserved:true,badPayloadRecovered:true,planThemeWinsOverBrowser:true,presetSendsKitchenCommand:true,errors}));
if(errors.length)process.exitCode=1;
await browser.close();
