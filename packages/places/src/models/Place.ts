/**
 * Place model - Core entity for hierarchical place management
 *
 * Supports both real-world places with geo data and abstract places
 * (virtual worlds, game zones) by making all geo fields optional.
 *
 * Tenancy: Places are tenant-scoped with optional mode, allowing:
 * - Tenant-specific places (tenantId set)
 * - Global/shared places (tenantId null)
 */

import type { Asset } from '@happyvertical/smrt-assets';
import {
  assertAssetLinkable,
  assertValidOwnedAssetRelationship,
  assertValidOwnedAssetSortOrder,
  resolveOwnedAssetsById,
} from '@happyvertical/smrt-assets';
import {
  field,
  foreignKey,
  SmrtHierarchical,
  smrt,
} from '@happyvertical/smrt-core';
import { TenantScoped, tenantId } from '@happyvertical/smrt-tenancy';
import type { GeoData, PlaceOptions } from '../types';

/** `place_assets.relationship` of a place's main picture. */
export const PLACE_MAIN_ASSET_RELATIONSHIP = 'hero';

@TenantScoped({ mode: 'optional' })
@smrt({
  tableStrategy: 'sti',
  api: { include: ['list', 'get', 'create', 'update', 'delete'] },
  mcp: { include: ['list', 'get', 'create', 'update'] },
  cli: { skipApiCheck: true },
})
export class Place extends SmrtHierarchical {
  // id: UUID (auto-generated by SmrtObject)

  // Tenancy field - nullable for global/shared places
  @tenantId({ nullable: true })
  tenantId: string | null = null;

  // Core fields
  @field({
    description:
      'What kind of place this is, such as a building, a room or a storage zone.',
  })
  @foreignKey('PlaceType')
  typeId = ''; // FK to PlaceType
  // parentId inherited from SmrtHierarchical (nullable, self-reference)
  @field({
    description:
      'What the place is called, such as "Main warehouse" or "Aisle 4".',
  })
  name = ''; // Place name/title
  @field({ description: 'A few words about the place and what happens there.' })
  description = ''; // Optional description

  // Optional geo fields (all nullable for abstract places)
  @field({
    type: 'decimal',
    description:
      'How far north or south the place is on a map. Leave empty for a place that is not on a map.',
  })
  latitude: number | null = null;
  @field({
    type: 'decimal',
    description:
      'How far east or west the place is on a map. Leave empty for a place that is not on a map.',
  })
  longitude: number | null = null;
  @field({ description: 'The number of the building on its street.' })
  streetNumber = '';
  @field({ description: 'The name of the street the place is on.' })
  streetName = '';
  @field({ description: 'The town or city the place is in.' })
  city = '';
  @field({ description: 'The state, province or region the place is in.' })
  region = '';
  @field({ description: 'The country the place is in.' })
  country = '';
  @field({ description: 'The postal or zip code of the address.' })
  postalCode = '';
  @field({
    description: 'The short two-letter code for the country, such as CA or US.',
  })
  countryCode = '';
  @field({
    description: 'The time zone the place keeps, such as America/Toronto.',
  })
  timezone = '';

  // Metadata
  @field({
    description:
      'The reference the map provider uses for this place, filled in when the app looks it up.',
  })
  externalId = ''; // External system identifier
  @field({
    description: 'Which map provider the place was looked up from, if any.',
  })
  source = ''; // Where this place came from (e.g., 'google', 'osm')
  metadata = ''; // JSON metadata stored as text

  // Timestamps
  createdAt = new Date();
  updatedAt = new Date();

  constructor(options: PlaceOptions = {}) {
    super(options);

    // Tenancy field
    if (options.tenantId !== undefined) this.tenantId = options.tenantId;

    // Core fields
    if (options.typeId) this.typeId = options.typeId;
    if (options.parentId !== undefined)
      this.parentId = options.parentId ?? null;
    if (options.name) this.name = options.name;
    if (options.description !== undefined)
      this.description = options.description;

    // Geo fields
    if (options.latitude !== undefined) this.latitude = options.latitude;
    if (options.longitude !== undefined) this.longitude = options.longitude;
    if (options.streetNumber !== undefined)
      this.streetNumber = options.streetNumber;
    if (options.streetName !== undefined) this.streetName = options.streetName;
    if (options.city !== undefined) this.city = options.city;
    if (options.region !== undefined) this.region = options.region;
    if (options.country !== undefined) this.country = options.country;
    if (options.postalCode !== undefined) this.postalCode = options.postalCode;
    if (options.countryCode !== undefined)
      this.countryCode = options.countryCode;
    if (options.timezone !== undefined) this.timezone = options.timezone;

    // Metadata
    if (options.externalId !== undefined) this.externalId = options.externalId;
    if (options.source !== undefined) this.source = options.source;

    // Handle metadata - can be object or JSON string
    if (options.metadata !== undefined) {
      if (typeof options.metadata === 'string') {
        this.metadata = options.metadata;
      } else {
        this.metadata = JSON.stringify(options.metadata);
      }
    }

    // Timestamps
    if (options.createdAt) this.createdAt = options.createdAt;
    if (options.updatedAt) this.updatedAt = options.updatedAt;
  }

  /**
   * Get geographic data for this place
   *
   * @returns GeoData object with all geo fields
   */
  getGeoData(): GeoData {
    return {
      latitude: this.latitude,
      longitude: this.longitude,
      streetNumber: this.streetNumber || undefined,
      streetName: this.streetName || undefined,
      city: this.city || undefined,
      region: this.region || undefined,
      country: this.country || undefined,
      postalCode: this.postalCode || undefined,
      countryCode: this.countryCode || undefined,
      timezone: this.timezone || undefined,
    };
  }

  /**
   * Check if this place has geographic coordinates
   *
   * @returns True if latitude and longitude are set
   */
  hasCoordinates(): boolean {
    return this.latitude !== null && this.longitude !== null;
  }

  /**
   * Get metadata as parsed object
   *
   * @returns Parsed metadata object or empty object if no metadata
   */
  getMetadata(): Record<string, unknown> {
    if (!this.metadata) return {};
    try {
      return JSON.parse(this.metadata);
    } catch {
      return {};
    }
  }

  /**
   * Set metadata from object
   *
   * @param data - Metadata object to store
   */
  setMetadata(data: Record<string, unknown>): void {
    this.metadata = JSON.stringify(data);
  }

  /**
   * Update metadata by merging with existing values
   *
   * @param updates - Partial metadata to merge
   */
  updateMetadata(updates: Record<string, unknown>): void {
    const current = this.getMetadata();
    this.setMetadata({ ...current, ...updates });
  }

  /**
   * Get the place type
   *
   * @returns PlaceType instance or null if not found
   */
  async getType() {
    if (!this.typeId) return null;

    const { PlaceTypeCollection } = await import(
      '../collections/PlaceTypeCollection'
    );
    const collection = await PlaceTypeCollection.create(this.options);

    return await collection.get({ id: this.typeId });
  }

  // Hierarchy traversal (getParent / getChildren / getAncestors /
  // getDescendants / getHierarchy / moveTo) provided by SmrtHierarchical.

  private async getPlaceAssetCollection() {
    const { PlaceAssetCollection } = await import(
      '../collections/PlaceAssetCollection'
    );
    return PlaceAssetCollection.create({ db: this.db });
  }
  async getAssets(relationship?: string): Promise<Asset[]> {
    if (!this.id) {
      return [];
    }

    const placeAssets = await this.getPlaceAssetCollection();
    const linkedAssets = await placeAssets.byLeft(
      this.id,
      relationship ? { relationship } : {},
    );

    return resolveOwnedAssetsById(
      this.db,
      linkedAssets.map((link) => link.assetId),
      this.tenantId,
    );
  }

  async addAsset(
    asset: Asset,
    relationship = 'attachment',
    sortOrder = 0,
  ): Promise<void> {
    if (!this.id || !asset.id) {
      throw new Error('Cannot associate unsaved place or asset');
    }
    // The asset's tenant comes from storage, not from the caller's object.
    await assertAssetLinkable(this.db, asset.id, this.tenantId, 'place');

    assertValidOwnedAssetRelationship(relationship);
    assertValidOwnedAssetSortOrder(sortOrder);

    const placeAssets = await this.getPlaceAssetCollection();
    await placeAssets.attach(this.id, asset.id, {
      relationship,
      sortOrder,
      tenantId: this.tenantId,
    });
  }

  /**
   * The place's main picture: its `hero` asset (see `ASSET_ROLES.HERO`), or
   * null when none is set.
   */
  async getMainAsset(): Promise<Asset | null> {
    const [main] = await this.getAssets(PLACE_MAIN_ASSET_RELATIONSHIP);
    return main ?? null;
  }

  /**
   * Make `asset` the place's one main picture: it becomes the only `hero`
   * link (any other is removed). Pass `null` to clear the main picture.
   * Other links of the asset (e.g. `depicts`) are left alone.
   */
  async setMainAsset(asset: Asset | null): Promise<void> {
    if (!this.id) {
      throw new Error('Cannot set the main asset of an unsaved place');
    }
    const placeAssets = await this.getPlaceAssetCollection();
    const current = await placeAssets.byLeft(this.id, {
      relationship: PLACE_MAIN_ASSET_RELATIONSHIP,
    });
    if (asset) await this.addAsset(asset, PLACE_MAIN_ASSET_RELATIONSHIP, 0);
    for (const link of current) {
      if (asset && link.assetId === asset.id) continue;
      await placeAssets.detach(this.id, link.assetId, {
        relationship: PLACE_MAIN_ASSET_RELATIONSHIP,
      });
    }
  }

  async removeAsset(assetId: string, relationship?: string): Promise<void> {
    if (!this.id) {
      return;
    }

    const placeAssets = await this.getPlaceAssetCollection();
    await placeAssets.detach(
      this.id,
      assetId,
      relationship ? { relationship } : {},
    );
  }
}
