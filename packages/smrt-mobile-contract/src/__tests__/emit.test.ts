import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { buildMobileContract } from '../build-contract.js';
import { generateKotlinDtoFiles } from '../emit-kotlin.js';
import { generateSwiftDtoFile } from '../emit-swift.js';
import type { SmrtManifest } from '../types.js';

const manifest: SmrtManifest = JSON.parse(
  readFileSync(
    join(import.meta.dirname, 'fixtures/sample-manifest.json'),
    'utf8',
  ),
);

const contract = buildMobileContract({
  manifests: [manifest],
  allowlist: ['FieldReport', 'Attachment'],
  kotlinPackage: 'com.example.generated',
  sourceLabel: 'fixtures/sample-manifest.json',
});

describe('generateKotlinDtoFiles', () => {
  const files = generateKotlinDtoFiles(contract);

  it('emits one file per DTO plus the contract manifest', () => {
    expect([...files.keys()].sort()).toEqual([
      'AttachmentDto.kt',
      'FieldReportDto.kt',
      'MobileContractManifest.kt',
    ]);
  });

  it('emits a small DTO exactly', () => {
    expect(files.get('AttachmentDto.kt')).toBe(
      `// Generated by @happyvertical/smrt-mobile-contract.
// Do not edit by hand.

package com.example.generated

import kotlinx.serialization.Serializable

@Serializable
data class AttachmentDto(
    val id: String,
    val fileName: String = "",
    val sizeBytes: Int = 0,
    val checksum: String = "",
)
`,
    );
  });

  it('imports framework and kotlinx types only when used', () => {
    const fieldReport = files.get('FieldReportDto.kt') ?? '';

    expect(fieldReport).toContain(
      'import com.happyvertical.smrt.mobile.contract.DecimalString',
    );
    expect(fieldReport).toContain('import kotlinx.datetime.Instant');
    expect(fieldReport).toContain(
      'import kotlinx.serialization.json.JsonObject',
    );
    expect(fieldReport).toContain('val confidence: DecimalString? = null,');
    expect(fieldReport).toContain('val created_at: Instant? = null,');

    const attachment = files.get('AttachmentDto.kt') ?? '';
    expect(attachment).not.toContain('kotlinx.datetime.Instant');
    expect(attachment).not.toContain('DecimalString');
  });

  it('records contract identity in MobileContractManifest.kt', () => {
    const manifestFile = files.get('MobileContractManifest.kt') ?? '';

    expect(manifestFile).toContain('package com.example.generated');
    expect(manifestFile).toContain(
      'const val MOBILE_CONTRACT_SCHEMA_VERSION: Int = 1',
    );
    expect(manifestFile).toContain(
      `const val MOBILE_CONTRACT_SOURCE_HASH: String = "${contract.sourceHash}"`,
    );
    expect(manifestFile).toContain('"FieldReport",');
    expect(manifestFile).toContain('"Attachment",');
  });
});

describe('generateSwiftDtoFile', () => {
  const swift = generateSwiftDtoFile(contract);

  it('emits plain structs with optionality mirroring Kotlin nullability', () => {
    expect(swift).toContain('struct FieldReportDto {');
    expect(swift).toContain('  let created_at: String?');
    expect(swift).toContain('  let confidence: String?');
    expect(swift).toContain('  let approved: Bool');
    expect(swift).toContain('  let metadataJson: String');
    expect(swift).toContain('struct AttachmentDto {');
  });

  it('stamps contract identity', () => {
    expect(swift).toContain(
      `let MobileContractSourceHash = "${contract.sourceHash}"`,
    );
    expect(swift).toContain('let MobileContractSchemaVersion = 1');
  });
});
