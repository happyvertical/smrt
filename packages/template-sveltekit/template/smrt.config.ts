import { resolveLocalRuntimePaths } from '@happyvertical/smrt-app-runtime';
import { resolveApplicationId } from './scripts/smrt-runtime-identity.mjs';

const profile = (process.env.SMRT_RUNTIME_PROFILE || 'local') as
  | 'local'
  | 'self-hosted'
  | 'cloud';
const appId = resolveApplicationId({
  sourceRoot: process.cwd(),
  explicitId: process.env.SMRT_APP_ID,
});
const localDatabase =
  profile === 'local'
    ? resolveLocalRuntimePaths({
        appId,
        dataDirectory: process.env.SMRT_DATA_DIR,
        sourceRoot: process.cwd(),
      }).database
    : undefined;

export default {
  // This is the single infrastructure selector for the application. Domain
  // objects and generated REST/CLI/MCP/WebMCP surfaces do not branch on it.
  runtime: {
    profile,
  },

  // Agent/developer knowledge artifacts are generated by smrtPlugin().
  // HTTP API routes stay off unless explicitly enabled for a dev/admin-only workflow.
  knowledge: {
    enabled: true,
    api: {
      enabled: false,
      basePath: '/__smrt/knowledge',
      requireAdmin: true,
      includeDocs: false,
      includePrompts: false,
    },
  },

  // Package-specific configuration
  packages: {
    // CLI configuration
    cli: {
      database: {
        type:
          profile === 'local' ? 'sqlite' : 'postgres',
        // `smrt-app` sets DATABASE_URL to the profile-owned data path before
        // migrations. Deployed profiles require an operator-owned URL.
        url:
          profile === 'local'
            ? process.env.DATABASE_URL || localDatabase
            : process.env.DATABASE_URL,
      },
      verbose: false,
    },

  },
};
