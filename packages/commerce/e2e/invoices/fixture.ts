function draftFor(kind: MoneyCase, roundingScope: Scope): MoneyEditorProps['draft'] {
  const exempt = kind === 'C' || kind === 'D';
  const lines = kind === 'E'
    ? ['rounding-a', 'rounding-b', 'rounding-c'].map(id => ({ id, description: `Rounding ${id}`, quantity: '1', unitPrice: '0.10', discountType: 'none' as const, discountValue: '0', taxMode: 'inherit' as const, inheritedTaxCodeId: 'gst-pst', inheritedTaxCodeSource: 'app' as const }))
    : epicLines.map(line => ({ ...line, inheritedTaxCodeId: exempt ? 'exempt' : line.inheritedTaxCodeId, inheritedTaxCodeSource: exempt ? 'exempt-customer' as const : line.inheritedTaxCodeSource }));
  return { currency: 'CAD', lineAmountType: goldenStored[kind][roundingScope].lineAmountType, roundingScope, lines };
}

export function moneyFixture(kind: MoneyCase = 'A', roundingScope: Scope = 'line', frozen = false): MoneyEditorProps {
  const fixture: MoneyEditorProps = {
    mode: 'v2', draft: draftFor(kind, roundingScope), taxCodes,
    customerTaxExempt: kind === 'C' || kind === 'D',
    sellerTaxRegistrations: ['GST/HST No. 123456789 RT0001'], partyTaxId: 'CA-Party-1', showNetSubtotal: true,
  };
  return frozen ? { ...fixture, frozen: true, status: 'SENT', stored: goldenStored[kind][roundingScope] } : fixture;
}

export function retainedMoney(data: URLSearchParams, kind: MoneyCase, roundingScope: Scope): MoneyEditorProps {
  const base = moneyFixture(kind, roundingScope);
  const row = (name: string, index: number) => String(data.getAll(name)[index] ?? '');
  return {
    ...base,
    draft: {
      ...base.draft,
      lineAmountType: (data.get('lineAmountType') as typeof base.draft.lineAmountType) || base.draft.lineAmountType,
      lines: data.getAll('lineId').map((id, index) => ({
        ...base.draft.lines[index], id: String(id), description: row('lineDescription', index), quantity: row('lineQuantity', index), unitPrice: row('lineUnitPrice', index), discountType: row('lineDiscountType', index) as 'none' | 'percent' | 'amount', discountValue: row('lineDiscountValue', index), taxMode: row('lineTaxMode', index) as 'inherit' | 'override', taxCodeId: row('lineTaxCodeId', index) || null,
      })),
    },
  };
}
