/**
 * ProfileType model - Lookup table defining profile types
 *
 * Represents the nature of a profile (e.g., 'human', 'org', 'robot').
 * Uses UUID primary key with unique slug for human-readable lookups.
 */

import {
  field,
  SmrtObject,
  type SmrtObjectOptions,
  smrt,
} from '@happyvertical/smrt-core';
import { TenantScoped, tenantId } from '@happyvertical/smrt-tenancy';
import {
  AGENT_PROFILE_TYPE_SLUG,
  AgentTypeChangeError,
  isUnprivilegedPrincipalContext,
} from '../agent-type-guard';

export interface ProfileTypeOptions extends SmrtObjectOptions {
  slug?: string;
  name?: string;
  description?: string;
  tenantId?: string | null;
}

@TenantScoped({ mode: 'optional' })
@smrt({
  tableStrategy: 'sti',
  api: { include: ['list', 'get', 'create', 'update'] },
  mcp: { include: ['list', 'get'] },
  cli: { skipApiCheck: true },
})
export class ProfileType extends SmrtObject {
  @tenantId({ nullable: true })
  tenantId: string | null = null;

  // id: UUID (auto-generated by SmrtObject)
  // slug is inherited from SmrtObject (auto-generated from name)
  @field()
  name: string = '';

  description?: string;

  constructor(options: ProfileTypeOptions = {}) {
    super(options);
    if (options.name) this.name = options.name;
    if (options.description !== undefined)
      this.description = options.description;
  }

  /**
   * An unprivileged principal cannot rename the `bot` type away or rename
   * another type to `bot` (#5086): the MCP principal kind is read from it.
   */
  override async save(
    options?: Parameters<SmrtObject['save']>[0],
  ): Promise<this> {
    if (isUnprivilegedPrincipalContext()) {
      const slug = this.slug || (await this.getSlug());
      let storedSlug: string | undefined;
      if (this.isPersisted && this.id) {
        const { ProfileTypeCollection } = await import(
          '../collections/ProfileTypeCollection'
        );
        const types = await ProfileTypeCollection.create(this.options);
        const stored = await types.get(this.id);
        if (!stored) throw new AgentTypeChangeError();
        storedSlug = stored.slug ?? undefined;
      }
      // Creating the `bot` type, renaming it away, or renaming onto it.
      if (
        (slug === AGENT_PROFILE_TYPE_SLUG && storedSlug !== slug) ||
        (storedSlug === AGENT_PROFILE_TYPE_SLUG && slug !== storedSlug)
      ) {
        throw new AgentTypeChangeError();
      }
    }
    return super.save(options);
  }

  /**
   * Convenience method for slug-based lookup
   *
   * @param slug - The slug to search for
   * @returns ProfileType instance or null if not found
   */
  static async getBySlug(_slug: string): Promise<ProfileType | null> {
    // Will be auto-implemented by SMRT
    return null;
  }
}
