/**
 * Canonical cross-profile surface inventory helpers (#2578).
 *
 * These helpers exist so that "the generated surface is identical under every
 * runtime profile" can be asserted as a byte-for-byte comparison instead of a
 * pile of per-field expectations. They read only PUBLIC generator output —
 * the real Vite plugin's emitted SvelteKit routes, `MCPGenerator`,
 * `generateOpenAPISpec()`, and `buildWebMcpToolDefinitions()`.
 * Nothing here reaches into registry or database private fields, and nothing
 * here re-implements a generator: a divergence in generated output has to
 * show up as a divergence in the canonical snapshot.
 *
 * There is no CLI inventory leg here: it used to read the plugin's emitted
 * `@happyvertical/smrt-virt-cli` module TEXT, which #2664 retired along with
 * core's `CLIGenerator` (unused public API, zero importers). The `cli` key in
 * each domain tool's `exposure` map is unaffected — it still reflects the
 * `@smrt()` decorator's `cli` config, which the live local transport
 * (`packages/cli/src/cli-generator.ts`) reads directly, independent of the
 * removed virtual module.
 * MCP is captured twice on purpose. `mcpToolNames` comes from the plugin's
 * per-copy emitted `smrt:mcp` module, so it is derived from THAT profile's
 * generation pass and would catch a copied-app divergence. `mcpToolSchemas`
 * comes from `MCPGenerator`, the generator the runtime MCP server resolves
 * against; it reads the process-wide `ObjectRegistry` and so is
 * profile-independent by construction — it proves schema shape, not
 * per-profile derivation. `generateOpenAPISpec()` is registry-scoped for the
 * same reason, which is why `assertOpenApiCoversGeneratedRest()` ties it back
 * to the per-copy generated routes.
 *
 * Public API (also consumed by the #2579 browser/CI aggregate):
 *
 * - {@link OPERATIONAL_DIAGNOSTIC_TOOL_NAME} — the ONE allowlisted operational
 *   entry that may legitimately differ from the domain surface. It is the
 *   authenticated read-only runtime diagnostic tool from #2577; it is authored
 *   by the template, not generated per model, so it is excluded from the
 *   domain inventories and asserted separately.
 * - {@link OPERATIONAL_DIAGNOSTIC_ROUTE} — that tool's authored route, the
 *   REST-side half of the same exception.
 * - {@link captureRuntimeProfileSurfaces} — build one profile's surfaces from
 *   a fresh copy of the reference app.
 * - {@link canonicalizeRuntimeProfileSurfaces} — stable JSON text for equality.
 * - {@link describeSurfaceDivergence} — actionable failure message.
 * - {@link canonicalizeJobOutcome} — identifier-free background-job result.
 */

import { type Dirent, readFileSync, readdirSync } from 'node:fs';
import { join, posix, relative, sep } from 'node:path';

import { MCPGenerator } from '@happyvertical/smrt-core/generators/mcp';
import { generateOpenAPISpec } from '@happyvertical/smrt-core/generators/swagger';
import {
  buildWebMcpToolDefinitions,
  smrtPlugin,
} from '@happyvertical/smrt-core/vite-plugin';
import type { SmartObjectManifest } from '@happyvertical/smrt-core/scanner';
import { resolveApplicationRuntime } from '@happyvertical/smrt-config';

import {
  type ReferenceRuntimeProfile,
  copyRuntimeProfileReference,
} from '../../fixtures/runtime-profile-reference/index.js';

/**
 * The single documented operational exception (#2547 milestone acceptance).
 * Kept as a literal rather than imported from the template module so that a
 * rename of the operational tool is a deliberate, reviewed snapshot change.
 */
export const OPERATIONAL_DIAGNOSTIC_TOOL_NAME =
  'smrt.runtime.diagnostics.read';

/** Authored (never generated) route backing the operational diagnostic tool. */
export const OPERATIONAL_DIAGNOSTIC_ROUTE = '_runtime/diagnostics';

/** Header every plugin-emitted route file starts with. */
const AUTO_GENERATED_ROUTE_HEADER = '// Auto-generated by @smrt/core vite plugin';

const ROUTES_DIR = 'src/routes/api';

const HTTP_METHODS = [
  'GET',
  'POST',
  'PUT',
  'PATCH',
  'DELETE',
  'OPTIONS',
  'HEAD',
] as const;

/** One generated REST route: its path below the API base and its verbs. */
export interface CanonicalRestRoute {
  readonly route: string;
  readonly methods: readonly string[];
  readonly generated: boolean;
}

/** One canonical domain tool, transport-independent policy included. */
export interface CanonicalDomainTool {
  readonly name: string;
  readonly collection: string;
  readonly action: string;
  readonly className: string;
  readonly objectRef: string;
  readonly endpoint: string;
  readonly idField: string;
  readonly idType: string;
  readonly inputSchema: unknown;
  readonly route: unknown;
  readonly relationships: unknown;
  /** Declared capability effect: read | write | destructive. */
  readonly effect: string;
  readonly readOnly: boolean;
  readonly idempotent: boolean;
  /** "external" annotation: may the tool act outside the application. */
  readonly openWorld: boolean;
  /** Caller-facing approval rule derived from the emitted effect. */
  readonly requiresApproval: boolean;
  /** Exposure policy: which transports declare this action. */
  readonly exposure: {
    readonly api: boolean;
    readonly cli: boolean;
    readonly mcp: boolean;
    readonly webMcp: boolean;
  };
  /** Tenant scope declared by `@TenantScoped`, or `none`. */
  readonly tenantScope: string;
}

/** Everything compared across profiles for one runtime profile selection. */
export interface RuntimeProfileSurfaces {
  readonly profile: ReferenceRuntimeProfile;
  /** Resolved composition — deliberately NOT part of the compared snapshot. */
  readonly composition: {
    readonly profile: string;
    readonly providers: unknown;
    readonly capabilities: unknown;
    readonly invariants: unknown;
  };
  readonly rest: readonly CanonicalRestRoute[];
  readonly openApiOperations: readonly string[];
  /** Per-copy MCP tool names, from this profile's emitted `smrt:mcp` module. */
  readonly mcpToolNames: readonly string[];
  /** Full MCP tool schemas from `MCPGenerator` (registry-scoped). */
  readonly mcpToolSchemas: readonly unknown[];
  readonly webMcpTools: readonly unknown[];
  readonly domainTools: readonly CanonicalDomainTool[];
  /** Names of allowlisted operational entries observed in this profile. */
  readonly operationalExceptions: readonly string[];
}

function walkRouteFiles(root: string, prefix = ''): string[] {
  // `ReturnType<typeof readdirSync>` resolves to the Buffer overload, so
  // `entry.name` types as a buffer and the `+server.ts` comparison below is
  // rejected. Name the element type the `withFileTypes` call actually returns.
  let entries: Dirent[];
  try {
    entries = readdirSync(root, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .flatMap((entry) =>
      entry.isDirectory()
        ? walkRouteFiles(join(root, entry.name), `${prefix}${entry.name}/`)
        : entry.name === '+server.ts'
          ? [`${prefix}${entry.name}`]
          : [],
    )
    .sort();
}

function collectRestRoutes(appRoot: string): CanonicalRestRoute[] {
  const routesRoot = join(appRoot, ...ROUTES_DIR.split('/'));
  return walkRouteFiles(routesRoot)
    .map((relativeFile) => {
      const absolute = join(routesRoot, ...relativeFile.split('/'));
      const source = readFileSync(absolute, 'utf8');
      const route =
        relative(routesRoot, absolute)
          .split(sep)
          .slice(0, -1)
          .join(posix.sep) || '.';
      return {
        route,
        methods: HTTP_METHODS.filter((method) =>
          new RegExp(`export const ${method}\\b`).test(source),
        ),
        generated: source.startsWith(AUTO_GENERATED_ROUTE_HEADER),
      };
    })
    .sort((left, right) => (left.route < right.route ? -1 : 1));
}

/** Class names the copied application itself owns (not framework packages). */
function domainClassNames(manifest: SmartObjectManifest): Set<string> {
  const owner = (manifest as { packageName?: string }).packageName;
  return new Set(
    Object.values(manifest.objects)
      .filter(
        (object) =>
          object.packageName === undefined || object.packageName === owner,
      )
      .map((object) => object.className),
  );
}

function tenantScopeOf(
  manifest: SmartObjectManifest,
  className: string,
): string {
  const object = Object.values(manifest.objects).find(
    (candidate) => candidate.className === className,
  );
  const scoped = (
    object?.decoratorConfig as { tenantScoped?: { mode?: string } } | undefined
  )?.tenantScoped;
  return scoped?.mode ?? 'none';
}

function transportIncludes(
  manifest: SmartObjectManifest,
  className: string,
  transport: 'api' | 'cli' | 'mcp',
  action: string,
): boolean {
  const object = Object.values(manifest.objects).find(
    (candidate) => candidate.className === className,
  );
  const config = object?.decoratorConfig?.[transport];
  if (config === false) return false;
  if (typeof config !== 'object' || config === null) return true;
  const include = (config as { include?: string[] }).include;
  const exclude = (config as { exclude?: string[] }).exclude ?? [];
  if (include && !include.includes(action)) return false;
  return !exclude.includes(action);
}

/**
 * Run the real SMRT Vite plugin against the copied app. This is the same code
 * path a scaffolded application runs at build time: it scans the sources,
 * writes `.smrt/manifest.json`, and emits the generated SvelteKit API routes.
 */
interface GenerationPass {
  readonly manifest: SmartObjectManifest;
  /** Raw emitted `@happyvertical/smrt-virt-mcp` module source. */
  readonly mcpModule: string;
}

async function runGenerationPass(appRoot: string): Promise<GenerationPass> {
  const plugin = smrtPlugin({
    projectRoot: appRoot,
    svelteKit: {
      enabled: true,
      routesDir: ROUTES_DIR,
      objectsDir: 'src/lib/objects',
      configPath: 'src/lib/server',
      configFileName: 'smrt.ts',
    },
  }) as unknown as {
    configResolved: (config: unknown) => Promise<void>;
    load: (id: string) => Promise<string>;
  };
  // `mode: 'test'` is the plugin's documented non-application build mode; it
  // keeps the consumer-plugin wiring check (which belongs to a real app build)
  // from firing for a fixture copy that is never bundled.
  await plugin.configResolved({
    mode: 'test',
    root: appRoot,
    plugins: [],
    build: {},
  });
  return {
    manifest: JSON.parse(
      readFileSync(join(appRoot, '.smrt', 'manifest.json'), 'utf8'),
    ) as SmartObjectManifest,
    mcpModule: await plugin.load('\0smrt:mcp'),
  };
}

/**
 * Extract the generated MCP tool-name inventory from the emitted module text.
 *
 * `export const tools = …` now holds the tool DEFINITION array (#2631 emits
 * `generateMCPToolsCode()` there; it previously interpolated a newline-joined
 * name list, which was not a valid expression). The names are read back from
 * each definition's `name:` property. This keeps the MCP inventory derived
 * from the SAME per-profile generation pass as the REST routes rather than
 * from process-wide state.
 */
function extractMcpToolNames(mcpModule: string): string[] {
  const assignment = /export const tools = ([\s\S]*?);\n/.exec(mcpModule);
  return [
    ...new Set(
      [...(assignment?.[1] ?? '').matchAll(/\bname:\s*"([^"]+)"/g)].map(
        (match) => match[1],
      ),
    ),
  ].sort();
}

/**
 * Copy the reference application, select `profile`, and capture every
 * generated surface it emits.
 *
 * The profile is selected exactly the way a deployed application selects it —
 * `SMRT_RUNTIME_PROFILE` plus the resolved runtime composition — and is held
 * for the whole capture so a profile-conditional generator would be observed.
 */
export async function captureRuntimeProfileSurfaces(
  appRoot: string,
  profile: ReferenceRuntimeProfile,
): Promise<RuntimeProfileSurfaces> {
  const previous = process.env.SMRT_RUNTIME_PROFILE;
  process.env.SMRT_RUNTIME_PROFILE = profile;
  try {
    const resolved = resolveApplicationRuntime({ profile });
    const fixture = copyRuntimeProfileReference(appRoot);
    const { manifest, mcpModule } = await runGenerationPass(fixture.root);

    const domainClasses = domainClassNames(manifest);
    const domainPrefixes = new Set(
      [...domainClasses].map((className) => className.toLowerCase()),
    );

    const rest = collectRestRoutes(fixture.root);
    const spec = generateOpenAPISpec({}) as {
      paths: Record<string, Record<string, unknown>>;
    };
    const openApiOperations = Object.entries(spec.paths)
      .flatMap(([path, item]) =>
        Object.keys(item)
          .filter((method) =>
            HTTP_METHODS.includes(
              method.toUpperCase() as (typeof HTTP_METHODS)[number],
            ),
          )
          .map((method) => `${method.toUpperCase()} ${path}`),
      )
      .filter((operation) =>
        [...domainPrefixes].some((prefix) =>
          operation.includes(`/${prefix}s`),
        ),
      )
      .sort();

    const mcpToolNames = extractMcpToolNames(mcpModule).filter((name) =>
      [...domainPrefixes].some(
        (prefix) => name.endsWith(`_${prefix}s`) || name.endsWith(`_${prefix}`),
      ),
    );

    const mcpToolSchemas = (await new MCPGenerator().generateTools())
      .filter((tool) =>
        [...domainPrefixes].some((prefix) =>
          tool.name.startsWith(`${prefix}_`),
        ),
      )
      .map((tool) => ({
        name: tool.name,
        description: tool.description,
        inputSchema: tool.inputSchema,
        outputSchema: tool.outputSchema,
      }))
      .sort((left, right) => (left.name < right.name ? -1 : 1));

    const webMcpDefinitions = buildWebMcpToolDefinitions(manifest).filter(
      (definition) => domainClasses.has(definition.className),
    );

    const domainTools: CanonicalDomainTool[] = webMcpDefinitions
      .map((definition) => ({
        name: definition.name,
        collection: definition.collection,
        action: definition.action,
        className: definition.className,
        objectRef: definition.objectRef,
        endpoint: definition.endpoint,
        idField: definition.idField,
        idType: definition.idType,
        inputSchema: definition.inputSchema,
        route: definition.route,
        relationships: definition.relationships,
        effect: definition.effect,
        readOnly: definition.readOnly,
        idempotent: definition.idempotent,
        openWorld: definition.openWorld,
        requiresApproval: definition.effect !== 'read',
        exposure: {
          api: transportIncludes(
            manifest,
            definition.className,
            'api',
            definition.action,
          ),
          cli: transportIncludes(
            manifest,
            definition.className,
            'cli',
            definition.action,
          ),
          mcp: transportIncludes(
            manifest,
            definition.className,
            'mcp',
            definition.action,
          ),
          webMcp: true,
        },
        tenantScope: tenantScopeOf(manifest, definition.className),
      }))
      .sort((left, right) => (left.name < right.name ? -1 : 1));

    return {
      profile,
      composition: {
        profile: resolved.profile,
        providers: resolved.providers,
        capabilities: resolved.capabilities,
        invariants: resolved.invariants,
      },
      rest,
      openApiOperations,
      mcpToolNames,
      mcpToolSchemas,
      webMcpTools: webMcpDefinitions,
      domainTools,
      operationalExceptions: rest
        .filter((entry) => entry.route === OPERATIONAL_DIAGNOSTIC_ROUTE)
        .map(() => OPERATIONAL_DIAGNOSTIC_TOOL_NAME),
    };
  } finally {
    if (previous === undefined) delete process.env.SMRT_RUNTIME_PROFILE;
    else process.env.SMRT_RUNTIME_PROFILE = previous;
  }
}

/** Recursively key-sorted JSON so equal structures serialize identically. */
function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === 'object') {
    const sorted: Record<string, unknown> = {};
    for (const key of Object.keys(value as Record<string, unknown>).sort()) {
      sorted[key] = canonicalize((value as Record<string, unknown>)[key]);
    }
    return sorted;
  }
  return value;
}

/**
 * Serialize the profile-invariant half of a capture.
 *
 * `profile` and `composition` are deliberately excluded: they are the inputs
 * that are SUPPOSED to differ. The allowlisted operational entry is excluded
 * from `rest` for the same reason and asserted separately by the caller.
 */
export function canonicalizeRuntimeProfileSurfaces(
  surfaces: RuntimeProfileSurfaces,
): string {
  return `${JSON.stringify(
    canonicalize({
      rest: surfaces.rest.filter(
        (entry) => entry.route !== OPERATIONAL_DIAGNOSTIC_ROUTE,
      ),
      openApiOperations: surfaces.openApiOperations,
      mcpToolNames: surfaces.mcpToolNames,
      mcpToolSchemas: surfaces.mcpToolSchemas,
      webMcpTools: surfaces.webMcpTools,
      domainTools: surfaces.domainTools,
    }),
    null,
    2,
  )}\n`;
}

/** Build an actionable, line-oriented divergence report for a failed match. */
export function describeSurfaceDivergence(
  baseline: RuntimeProfileSurfaces,
  candidate: RuntimeProfileSurfaces,
): string {
  const left = canonicalizeRuntimeProfileSurfaces(baseline).split('\n');
  const right = canonicalizeRuntimeProfileSurfaces(candidate).split('\n');
  const differences: string[] = [];
  for (let line = 0; line < Math.max(left.length, right.length); line += 1) {
    if (left[line] === right[line]) continue;
    differences.push(
      `  line ${line + 1}:\n    ${baseline.profile}: ${left[line] ?? '<absent>'}\n    ${candidate.profile}: ${right[line] ?? '<absent>'}`,
    );
    if (differences.length >= 20) break;
  }
  return [
    `Generated surface differs between the "${baseline.profile}" and "${candidate.profile}" runtime profiles.`,
    'Runtime profiles select infrastructure, never the domain surface: REST, CLI,',
    'MCP, WebMCP, action effects, approval policy, exposure, and tenant scope must',
    `be identical. The only allowlisted operational exception is "${OPERATIONAL_DIAGNOSTIC_TOOL_NAME}".`,
    'If this change is intended, fix the generator that branched on profile — do not',
    'update the snapshot to describe the divergence.',
    '',
    ...differences,
  ].join('\n');
}

/**
 * Identifier-free background-job outcome, comparable across topologies.
 *
 * The observable domain result of a background action is the state of the
 * domain record it mutated, not a transport-specific return envelope: a job
 * row stores only a `resultPointer`, so asserting on the record is both the
 * portable comparison and the one an application actually depends on.
 */
export interface CanonicalJobOutcome {
  readonly queue: string;
  readonly method: string;
  readonly jobStatus: string;
  readonly record: {
    readonly title: string;
    readonly status: string;
    readonly priority: number;
  };
}

/** Normalize one completed job plus its domain record into a stable shape. */
export function canonicalizeJobOutcome(input: {
  queue: unknown;
  method: unknown;
  jobStatus: unknown;
  record: { title: unknown; status: unknown; priority: unknown };
}): CanonicalJobOutcome {
  return {
    queue: String(input.queue),
    method: String(input.method),
    jobStatus: String(input.jobStatus),
    record: {
      title: String(input.record.title),
      status: String(input.record.status),
      priority: Number(input.record.priority),
    },
  };
}

/**
 * The canonical domain result of the reference application's one
 * background-capable workflow.
 *
 * Both job topologies — local embedded/on-demand execution and the
 * self-hosted PostgreSQL external worker — must produce exactly this.
 */
export const REFERENCE_JOB_OUTCOME: CanonicalJobOutcome = {
  queue: 'reference-workload',
  method: 'prepareForReview',
  jobStatus: 'completed',
  record: { title: 'Reference workload', status: 'queued', priority: 50 },
};

/**
 * Tie the registry-scoped OpenAPI document back to the per-copy generated
 * REST routes.
 *
 * `generateOpenAPISpec()` reads the process-wide `ObjectRegistry`, so on its
 * own it cannot witness a copied-app REST change. Requiring every generated
 * domain collection route to appear as an OpenAPI operation closes that gap:
 * a REST surface that the OpenAPI document does not describe fails here.
 * Returns the generated collection routes that OpenAPI omits.
 */
export function openApiGapsAgainstGeneratedRest(
  surfaces: RuntimeProfileSurfaces,
  collection: string,
): string[] {
  const described = new Set(
    surfaces.openApiOperations
      .filter((operation) => operation.includes(`/${collection}`))
      .map((operation) => {
        const [method, path] = operation.split(' ');
        return `${method} ${(path as string).endsWith('{id}') ? `${collection}/[id]` : collection}`;
      }),
  );
  return surfaces.rest
    .filter(
      (route) =>
        route.generated &&
        (route.route === collection || route.route === `${collection}/[id]`),
    )
    .flatMap((route) =>
      route.methods.map((method) => `${method} ${route.route}`),
    )
    .filter((operation) => !described.has(operation))
    .sort();
}
