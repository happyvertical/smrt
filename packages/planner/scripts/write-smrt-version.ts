/**
 * Write `src/lib/smrt-version.ts` from the installed `@happyvertical/smrt-core`.
 *
 * The Export page names the released `smrt` CLI in the commands it shows
 * (`npx -y @happyvertical/smrt-cli@<version> …`). Every smrt package is
 * released in lockstep, so the installed smrt-core version is the CLI version
 * the planner was built against. No smrt package exports its `package.json`,
 * so the version is copied into a constant here; `pnpm package` runs this
 * first and `tests/smrt-version.test.ts` fails when the constant drifts.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(
  readFileSync(
    new URL(
      '../node_modules/@happyvertical/smrt-core/package.json',
      import.meta.url,
    ),
    'utf8',
  ),
) as { version: string };

const file = new URL('../src/lib/smrt-version.ts', import.meta.url);
const text = `// Generated by scripts/write-smrt-version.ts from the installed
// @happyvertical/smrt-core; do not edit. \`pnpm version:smrt\` refreshes it.

/** The released smrt line the planner is built against (the \`smrt\` CLI version its commands name). */
export const SMRT_VERSION = '${version}';
`;
const current = (() => {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return '';
  }
})();
if (current !== text) {
  writeFileSync(file, text);
  console.log(`src/lib/smrt-version.ts: ${version}`);
}
