/**
 * Vite plugin for generating SvelteKit route files from agent admin route declarations.
 *
 * Reads agent manifests at build time and generates thin SvelteKit wrapper files
 * (+page.svelte and +page.server.ts) that delegate to agent-provided components
 * and load functions.
 *
 * @example
 * ```typescript
 * // vite.config.ts
 * import { vitePluginAgentRoutes } from '@happyvertical/smrt-agents/vite';
 *
 * export default defineConfig({
 *   plugins: [
 *     sveltekit(),
 *     vitePluginAgentRoutes({
 *       agents: [
 *         { packageName: '@happyvertical/praeco', agentClass: 'Praeco' },
 *         { packageName: '@happyvertical/caelus', agentClass: 'Caelus' },
 *       ],
 *     }),
 *   ],
 * });
 * ```
 */

import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import type { Plugin } from 'vite';

const require = createRequire(import.meta.url);

/**
 * Configuration for each agent whose routes should be generated
 */
export interface AgentRouteConfig {
  /** Package name (e.g., '@happyvertical/praeco') */
  packageName: string;
  /** Agent class name (e.g., 'Praeco') — used for route grouping and registry lookups */
  agentClass: string;
  /** Admin export subpath (default: 'admin') — the package.json export that provides components and load functions */
  adminExport?: string;
}

/**
 * Options for the vitePluginAgentRoutes Vite plugin
 */
export interface AgentRoutesPluginOptions {
  /**
   * Where to write generated route files, relative to project root.
   * Default: 'src/routes/portal/[siteSlug]/agents/[agentId]'
   */
  routeBase?: string;
  /** Agent packages to generate routes for */
  agents: AgentRouteConfig[];
}

/** Route definition from the agent manifest */
interface ManifestRoute {
  path: string;
  component: string;
  load?: string;
}

/**
 * Validate a route path to prevent path traversal and invalid routes.
 * Returns true if the path is safe to use for file generation.
 */
export function isValidRoutePath(path: string): boolean {
  if (!path || !path.trim()) return false;
  if (path.includes('..')) return false;
  if (path.startsWith('/')) return false;
  if (path.includes('\\')) return false;
  // Disallow null bytes
  if (path.includes('\0')) return false;
  return true;
}

/**
 * Generate the content for a +page.svelte wrapper file
 */
export function generatePageSvelte(
  packageName: string,
  adminExport: string,
  componentName: string,
): string {
  const importPath = `${packageName}/${adminExport}`;
  return `<script lang="ts">
  // AUTO-GENERATED by vitePluginAgentRoutes — do not edit
  import { ${componentName} } from '${importPath}';
  let { data } = $props();
</script>
<${componentName} {...data} />
`;
}

/**
 * Generate the content for a +page.server.ts wrapper file
 */
export function generatePageServerTs(
  packageName: string,
  adminExport: string,
  loadFnName: string,
): string {
  const importPath = `${packageName}/${adminExport}`;
  return `// AUTO-GENERATED by vitePluginAgentRoutes — do not edit
import type { PageServerLoad } from './$types';
import { ${loadFnName} } from '${importPath}';

export const load: PageServerLoad = async (event) => {
  return ${loadFnName}({
    params: event.params,
    parent: event.parent,
    fetch: event.fetch,
    url: event.url,
  });
};
`;
}

/**
 * Convert a route path to a SvelteKit route directory structure.
 *
 * Agent route paths like 'sources/[sourceId]/edit' become
 * '(praeco)/sources/[sourceId]/edit' — the route group prevents
 * collisions between agents (the group name is invisible in URLs).
 */
export function routePathToDir(agentSlug: string, routePath: string): string {
  return `(${agentSlug})/${routePath}`;
}

/**
 * Read agent manifest from a package, extracting adminRoutes for the given agent class
 */
function readAgentRoutes(
  packageName: string,
  agentClass: string,
): ManifestRoute[] {
  try {
    // Resolve the manifest.json from the package
    const manifestPath = require.resolve(`${packageName}/manifest.json`);
    const manifest = require(manifestPath);

    // Find the agent object in the manifest
    const agentSlug = agentClass.toLowerCase();
    for (const obj of Object.values(manifest.objects ?? {})) {
      const objDef = obj as any;
      if (objDef.agent && objDef.agent.slug === agentSlug) {
        return objDef.agent.adminRoutes ?? [];
      }
    }

    return [];
  } catch (err) {
    console.warn(
      `[vite-plugin-agent-routes] Could not read manifest for ${packageName}: ${err}`,
    );
    return [];
  }
}

/**
 * Write a file, creating parent directories as needed
 */
async function writeFileWithDirs(
  filePath: string,
  content: string,
): Promise<boolean> {
  const { mkdir, readFile, writeFile } = await import('node:fs/promises');

  await mkdir(dirname(filePath), { recursive: true });

  // Only write if content has changed (avoid unnecessary HMR triggers)
  try {
    const existing = await readFile(filePath, 'utf-8');
    if (existing === content) return false;
  } catch {
    // File doesn't exist yet — write it
  }

  await writeFile(filePath, content, 'utf-8');
  return true;
}

/**
 * Generate all route files for a single agent
 */
async function generateAgentRouteFiles(
  agent: AgentRouteConfig,
  routes: ManifestRoute[],
  routeBaseDir: string,
): Promise<number> {
  const agentSlug = agent.agentClass.toLowerCase();
  const adminExport = agent.adminExport ?? 'admin';
  let filesWritten = 0;

  for (const route of routes) {
    if (!isValidRoutePath(route.path)) {
      console.warn(
        `[vite-plugin-agent-routes] Skipping invalid route path for ${agent.agentClass}: ${JSON.stringify(route.path)}`,
      );
      continue;
    }
    if (!route.component) {
      console.warn(
        `[vite-plugin-agent-routes] Skipping route with no component for ${agent.agentClass}: ${route.path}`,
      );
      continue;
    }

    const routeDir = join(routeBaseDir, routePathToDir(agentSlug, route.path));

    // Generate +page.svelte
    const pageSvelteContent = generatePageSvelte(
      agent.packageName,
      adminExport,
      route.component,
    );
    const pageSveltePath = join(routeDir, '+page.svelte');
    if (await writeFileWithDirs(pageSveltePath, pageSvelteContent)) {
      filesWritten++;
    }

    // Generate +page.server.ts (only if load function is specified)
    if (route.load) {
      const pageServerContent = generatePageServerTs(
        agent.packageName,
        adminExport,
        route.load,
      );
      const pageServerPath = join(routeDir, '+page.server.ts');
      if (await writeFileWithDirs(pageServerPath, pageServerContent)) {
        filesWritten++;
      }
    }
  }

  return filesWritten;
}

/**
 * Write a .gitignore in the generated route group directory
 */
async function writeGitignore(
  routeBaseDir: string,
  agentSlug: string,
): Promise<void> {
  const { mkdir, writeFile } = await import('node:fs/promises');
  const groupDir = join(routeBaseDir, `(${agentSlug})`);
  await mkdir(groupDir, { recursive: true });
  await writeFile(
    join(groupDir, '.gitignore'),
    '# AUTO-GENERATED by vitePluginAgentRoutes — do not edit\n*\n',
    'utf-8',
  );
}

/**
 * Vite plugin that generates SvelteKit route files from agent admin route declarations.
 *
 * Reads agent manifests at build time and generates thin SvelteKit wrapper files
 * that delegate to agent-provided components and load functions.
 *
 * Generated routes use SvelteKit route groups to namespace per-agent
 * (e.g., `[agentId]/(praeco)/sources/[sourceId]/`), keeping URLs clean
 * while preventing route collisions between agents.
 */
export function vitePluginAgentRoutes(
  options: AgentRoutesPluginOptions,
): Plugin {
  const routeBase =
    options.routeBase ?? 'src/routes/portal/[siteSlug]/agents/[agentId]';

  let projectRoot: string;

  async function generateAllRoutes(): Promise<void> {
    const routeBaseDir = resolve(projectRoot, routeBase);

    for (const agent of options.agents) {
      const routes = readAgentRoutes(agent.packageName, agent.agentClass);

      if (routes.length === 0) continue;

      const agentSlug = agent.agentClass.toLowerCase();

      // Write .gitignore for the generated route group
      await writeGitignore(routeBaseDir, agentSlug);

      const filesWritten = await generateAgentRouteFiles(
        agent,
        routes,
        routeBaseDir,
      );

      if (filesWritten > 0) {
        console.log(
          `[vite-plugin-agent-routes] Generated ${filesWritten} route files for ${agent.agentClass}`,
        );
      }
    }
  }

  return {
    name: 'vite-plugin-agent-routes',
    enforce: 'pre',

    configResolved(config) {
      projectRoot = config.root;
    },

    async buildStart() {
      await generateAllRoutes();
    },

    configureServer(server) {
      // Re-generate routes when manifest files change
      server.watcher.on('change', async (filePath) => {
        if (filePath.endsWith('manifest.json')) {
          // Check if this is a manifest we care about
          for (const agent of options.agents) {
            try {
              const manifestPath = require.resolve(
                `${agent.packageName}/manifest.json`,
              );
              if (filePath === manifestPath) {
                console.log(
                  `[vite-plugin-agent-routes] Manifest changed for ${agent.agentClass}, regenerating routes...`,
                );
                // Clear the require cache for the changed manifest
                delete require.cache[manifestPath];
                await generateAllRoutes();
                break;
              }
            } catch {
              // Package not found — skip
            }
          }
        }
      });
    },
  };
}
