/**
 * Reviewed loader-parity exceptions, keyed by divergence id (a qualified key,
 * or `<key> (under <package>)` for a dependency key), each pinned to the
 * reviewed difference between the two sides (`parityDifference`). Ids only
 * leave; the file itself persists, as an empty list when nothing diverges.
 */
export const PARITY_KNOWN_FILE = 'loader-parity-known.json';
/** Packages whose built root does not load under plain Node (check:node-roots). */
export const NODE_ROOT_ALLOW = ['@happyvertical/smrt-products'];

const HEADER = [
  '# Generated by scripts/check-served-surface.mjs. Do not edit; run pnpm surface:served.',
  '# One line per model or collection this package declares: the REST resource path,',
  '# CRUD and actions (verb, scope, route, auth, permission slug), MCP tools and',
  '# CLI commands (operations and the names a client calls) it serves when loaded',
  '# from its built manifest with its smrtDependencies closure.',
  '# Not modelled: the REST tenant-context guard; runtime replacements and',
  '# overrides; compositions of two or more dependents; run-time-only models.',
];

const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** `served-surface/<file>` for a package: its name without the scope. */
export function surfaceFileName(packageName) {
  return `${packageName.replace(/^@[^/]+\//, '')}.txt`;
}

/** Packages under `packages/` with a built manifest, by package name. */
export function findPackages(root) {
  const packages = new Map();
  const dir = path.join(root, 'packages');
  if (!existsSync(dir)) return packages;
  for (const name of readdirSync(dir).sort(byCodeUnit)) {
    const pkgJson = path.join(dir, name, 'package.json');
    if (!existsSync(pkgJson)) continue;
    for (const rel of ['dist/manifest.json', 'dist/lib/manifest.json']) {
      const manifestPath = path.join(dir, name, rel);
      if (!existsSync(manifestPath)) continue;
      const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
      const packageName =
        manifest.packageName ?? JSON.parse(readFileSync(pkgJson, 'utf8')).name;
      packages.set(packageName, {
        packageName,
        dir: path.join(dir, name),
        manifestPath,
        manifest,
      });
      break;
    }
  }
  return packages;
}

/**
 * The transitive `smrtDependencies` closure of `packageName`, dependencies
 * first. Names with no built manifest are returned in `missing`.
 */
export function dependencyClosure(packageName, packages) {
  const order = [];
  const missing = [];
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    const pkg = packages.get(name);
    if (!pkg) {
      missing.push(name);
      return;
    }
    for (const dep of [...(pkg.manifest.smrtDependencies ?? [])].sort(byCodeUnit))
      visit(dep);
    order.push(name);
  };
  visit(packageName);
  return { order, missing };
}

function runWorker(job) {
  return new Promise((resolve) => {
    const cwd = mkdtempSync(path.join(tmpdir(), 'served-surface-cwd-'));
    const jobFile = path.join(cwd, 'job.json');
    const outFile = path.join(cwd, 'out.json');
    writeFileSync(jobFile, JSON.stringify({ ...job, outFile }));
    const child = spawn(process.execPath, [WORKER, jobFile], {
      cwd,
      env: { ...process.env, SMRT_VERBOSE: '', DEBUG: '' },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stderr = '';
    child.stdout.on('data', () => {});
    child.stderr.on('data', (chunk) => {
      stderr += chunk;
    });
    child.on('close', (code) => {
      let result;
      try {
        result = JSON.parse(readFileSync(outFile, 'utf8'));
      } catch {
        result = {
          errors: [
            `${job.packageName}: worker exited ${code} without a result: ${stderr.trim().split('\n').slice(-5).join(' | ')}`,
          ],
        };
      }
      rmSync(cwd, { recursive: true, force: true });
      resolve(result);
    });
  });
}

async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let next = 0;
  const runners = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index], index);
    }
  });
  await Promise.all(runners);
  return results;
}

const canonicalSurface = (value) => {
  if (!value) return false;
  const out = {};
  for (const key of Object.keys(value).sort(byCodeUnit)) out[key] = value[key];
  return out;
};

function lineFor(entry) {
  const ordered = { key: entry.key, kind: entry.kind };
  if (entry.owner && entry.owner !== entry.key) ordered.owner = entry.owner;
  if (entry.internal) ordered.internal = entry.internal;
  if (entry.src) ordered.src = entry.src;
  if (entry.flags?.length) ordered.flags = entry.flags;
  ordered.api = canonicalSurface(entry.api);
  ordered.mcp = canonicalSurface(entry.mcp);
  ordered.cli = canonicalSurface(entry.cli);
  return JSON.stringify(ordered);
}

function shadowLine(shadow) {
  return JSON.stringify({
    shadow: shadow.key,
    owner: shadow.owner,
    api: canonicalSurface(shadow.api),
    mcp: canonicalSurface(shadow.mcp),
    cli: canonicalSurface(shadow.cli),
  });
}

/** The canonical text of one package's snapshot. */
export function serializePackage(packageName, data) {
  const lines = [...HEADER, `# package ${packageName}`];
  for (const entry of [...data.entries].sort((a, b) => byCodeUnit(a.key, b.key)))
    lines.push(lineFor(entry));
  for (const shadow of [...data.shadows].sort((a, b) => byCodeUnit(a.key, b.key)))
    lines.push(shadowLine(shadow));
  for (const mask of [...(data.masked ?? [])].sort((a, b) => byCodeUnit(a.key, b.key)))
    lines.push(JSON.stringify({ masked: mask.key, surface: mask.surface, by: mask.by }));
  for (const name of [...data.unmarked].sort(byCodeUnit))
    lines.push(JSON.stringify({ unmarkedDependency: name }));
  for (const key of [...data.ambiguous].sort(byCodeUnit))
    lines.push(JSON.stringify({ ambiguous: key }));
  return `${lines.join('\n')}\n`;
}

/** Parse a snapshot file into entries, shadows, masks, unmarked deps, ambiguous keys. */
export function parseSurfaceFile(text) {
  const parsed = { entries: new Map(), shadows: [], masked: [], unmarked: [], ambiguous: [] };
  for (const line of text.split('\n')) {
    if (!line.startsWith('{')) continue;
    const value = JSON.parse(line);
    if ('key' in value) parsed.entries.set(value.key, value);
    else if ('shadow' in value) parsed.shadows.push(value);
    else if ('masked' in value) parsed.masked.push(value);
    else if ('unmarkedDependency' in value) parsed.unmarked.push(value.unmarkedDependency);
    else if ('ambiguous' in value) parsed.ambiguous.push(value.ambiguous);
  }
  return parsed;
}

const PUBLIC_RANK = { false: 0, read: 1, true: 2 };
const publicOf = (api) => String(api ? (api.public ?? false) : false);
const opsOf = (surface, field = 'ops') =>
  new Set(surface && Array.isArray(surface[field]) ? surface[field] : []);
/** A surface's `tools` / `commands` as address -> operation. */
const addressesOf = (surface, field) => {
  const value = surface && surface[field];
  return new Map(
    value && typeof value === 'object' && !Array.isArray(value)
      ? Object.entries(value)
      : [],
  );
};

function compareSurfaces(key, before, after, push) {
  for (const [surface, field, noun] of [
    ['mcp', 'tools', 'tool'],
    ['cli', 'commands', 'command'],
  ]) {
    const old = opsOf(before?.[surface]);
    const now = opsOf(after?.[surface]);
    for (const op of now) if (!old.has(op)) push('WIDEN', key, `${surface} +${op}`);
    for (const op of old) if (!now.has(op)) push('NARROW', key, `${surface} -${op}`);
    // The names a client calls and what each runs: a rename moves the
    // address, a reassignment changes what a call does.
    const oldNames = addressesOf(before?.[surface], field);
    const newNames = addressesOf(after?.[surface], field);
    for (const [name, op] of newNames) {
      if (!oldNames.has(name)) push('CHANGED', key, `${surface} ${noun} name +${name}`);
      else if (oldNames.get(name) !== op)
        push('CHANGED', key, `${surface} ${noun} ${name} now runs ${op} (was ${oldNames.get(name)})`);
    }
    for (const name of oldNames.keys())
      if (!newNames.has(name)) push('CHANGED', key, `${surface} ${noun} name -${name}`);
  }
  if ((before?.api?.path ?? null) !== (after?.api?.path ?? null))
    push('CHANGED', key, `api path ${before?.api?.path ?? '-'} -> ${after?.api?.path ?? '-'}`);
  const oldCrud = opsOf(before?.api, 'crud');
  const newCrud = opsOf(after?.api, 'crud');
  for (const op of newCrud) if (!oldCrud.has(op)) push('WIDEN', key, `api +${op}`);
  for (const op of oldCrud) if (!newCrud.has(op)) push('NARROW', key, `api -${op}`);
  const oldCrudPermission = before?.api?.crudPermission ?? null;
  const newCrudPermission = after?.api?.crudPermission ?? null;
  if (oldCrudPermission !== newCrudPermission)
    // As for an action slug: dropping the check widens, adding one narrows,
    // and a different collection admits a different set of principals.
    push(
      newCrudPermission && !oldCrudPermission ? 'NARROW' : 'WIDEN',
      key,
      `api crud permission ${oldCrudPermission ?? '-'} -> ${newCrudPermission ?? '-'}`,
    );
  const oldActions = (before?.api && before.api.actions) || {};
  const newActions = (after?.api && after.api.actions) || {};
  for (const [name, action] of Object.entries(newActions)) {
    const prior = oldActions[name];
    if (!prior) {
      push('WIDEN', key, `api action ${name} added (${action.verb})`);
      continue;
    }
    if (prior.verb !== action.verb) {
      const opens = prior.verb !== 'GET' && action.verb === 'GET';
      push(
        opens ? 'WIDEN' : 'CHANGED',
        key,
        `api action ${name} verb ${prior.verb} -> ${action.verb}`,
      );
    }
    if (prior.auth !== action.auth)
      push(
        action.auth === 'open' ? 'WIDEN' : 'NARROW',
        key,
        `api action ${name} auth ${prior.auth} -> ${action.auth}`,
      );
    if (prior.permission !== action.permission)
      // Dropping the check widens; adding one narrows; a different slug
      // admits a different set of principals.
      push(
        action.permission && !prior.permission ? 'NARROW' : 'WIDEN',
        key,
        `api action ${name} permission ${prior.permission} -> ${action.permission}`,
      );
    if (prior.scope !== action.scope)
      push('CHANGED', key, `api action ${name} scope ${prior.scope} -> ${action.scope}`);
    if ((prior.route ?? null) !== (action.route ?? null))
      push('CHANGED', key, `api action ${name} route ${prior.route ?? '-'} -> ${action.route ?? '-'}`);
  }
  for (const name of Object.keys(oldActions))
    if (!newActions[name]) push('NARROW', key, `api action ${name} removed`);
  const oldPublic = publicOf(before?.api);
  const newPublic = publicOf(after?.api);
  if (oldPublic !== newPublic)
    push(
      PUBLIC_RANK[newPublic] > PUBLIC_RANK[oldPublic] ? 'WIDEN' : 'NARROW',
      key,
      `public ${oldPublic} -> ${newPublic}`,
    );
}

const serves = (entry) =>
  ['api', 'mcp', 'cli'].some((surface) => entry[surface] && entry[surface] !== false);

/**
 * Classified differences between two snapshots of one package: WIDEN,
 * NARROW, NEW, GONE, and CHANGED (metadata that neither opens nor closes).
 */
export function classifyChanges(beforeText, afterText) {
  const before = parseSurfaceFile(beforeText ?? '');
  const after = parseSurfaceFile(afterText ?? '');
  const changes = [];
  const push = (cls, key, detail) => changes.push({ class: cls, key, detail });
  for (const [key, entry] of after.entries) {
    const prior = before.entries.get(key);
    if (!prior) {
      push('NEW', key, serves(entry) ? 'new key, served' : 'new key, not served');
      continue;
    }
    if ((prior.owner ?? key) !== (entry.owner ?? key))
      push('WIDEN', key, `owner ${prior.owner ?? key} -> ${entry.owner ?? key}`);
    compareSurfaces(key, prior, entry, push);
    for (const field of ['kind', 'internal', 'src'])
      if ((prior[field] ?? null) !== (entry[field] ?? null))
        push('CHANGED', key, `${field} ${prior[field] ?? '-'} -> ${entry[field] ?? '-'}`);
    if ((prior.flags ?? []).join() !== (entry.flags ?? []).join())
      push(
        'CHANGED',
        key,
        `flags [${(prior.flags ?? []).join(',')}] -> [${(entry.flags ?? []).join(',')}]`,
      );
  }
  for (const key of before.entries.keys())
    if (!after.entries.has(key)) push('GONE', key, 'key removed');
  const shadowsOf = (parsed) => new Map(parsed.shadows.map((s) => [s.shadow, s]));
  const oldShadows = shadowsOf(before);
  const newShadows = shadowsOf(after);
  for (const [key, shadow] of newShadows) {
    const prior = oldShadows.get(key);
    if (!prior) {
      push('WIDEN', key, `now replaced by ${shadow.owner}`);
      continue;
    }
    if (prior.owner !== shadow.owner)
      push('WIDEN', key, `replacement ${prior.owner} -> ${shadow.owner}`);
    compareSurfaces(key, prior, shadow, push);
  }
  for (const [key, shadow] of oldShadows)
    if (!newShadows.has(key)) push('NARROW', key, `no longer replaced by ${shadow.owner}`);
  const masksOf = (parsed) => new Map(parsed.masked.map((m) => [m.masked, m]));
  const oldMasks = masksOf(before);
  const newMasks = masksOf(after);
  for (const [key, mask] of newMasks)
    if (oldMasks.get(key)?.by !== mask.by)
      push('CHANGED', key, `${mask.surface} commands now served by ${mask.by}`);
  for (const [key, mask] of oldMasks)
    if (!newMasks.has(key)) push('CHANGED', key, `${mask.surface} commands no longer served by ${mask.by}`);
  for (const name of after.unmarked)
    if (!before.unmarked.includes(name))
      push('WIDEN', name, 'dependency manifest lost its exposure-rule marker');
  for (const name of before.unmarked)
    if (!after.unmarked.includes(name))
      push('CHANGED', name, 'dependency manifest now carries the exposure-rule marker');
  for (const key of after.ambiguous)
    if (!before.ambiguous.includes(key)) push('CHANGED', key, 'now ambiguous');
  for (const key of before.ambiguous)
    if (!after.ambiguous.includes(key)) push('CHANGED', key, 'no longer ambiguous');
  return changes;
}

/** Canonical JSON: keys sorted at every level. */
export function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object')
    return `{${Object.keys(value)
      .sort(byCodeUnit)
      .map((k) => `${JSON.stringify(k)}:${canonicalJson(value[k])}`)
      .join(',')}}`;
  return JSON.stringify(value ?? null);
}

/** One surface of a served tuple as comparable facts, one string each. */
function surfaceAtoms(surface, value) {
  if (!value) return [];
  if (surface === 'api') {
    const atoms = [`path ${value.path}`];
    for (const verb of value.crud ?? []) atoms.push(`crud ${verb}`);
    if (value.crudPermission) atoms.push(`crudPermission ${value.crudPermission}`);
    if (value.public) atoms.push(`public ${value.public}`);
    for (const [name, action] of Object.entries(value.actions ?? {}))
      atoms.push(`action ${name} ${canonicalJson(action)}`);
    return atoms;
  }
  const [field, noun] = surface === 'mcp' ? ['tools', 'tool'] : ['commands', 'command'];
  const atoms = (value.ops ?? []).map((op) => `op ${op}`);
  for (const [name, op] of addressesOf(value, field)) atoms.push(`${noun} ${name} -> ${op}`);
  return atoms;
}

/**
 * What loader parity pins: only what one side serves and the other does not,
 * per surface (`{ owner?, api?, mcp?, cli? }`, each surface as
 * `{ manifestOnly, builtRootOnly }`). A change both sides make alike (a new
 * method served either way, a core-wide rename) leaves it unchanged. Empty
 * exactly when the two tuples are equal.
 */
export function parityDifference(manifest, builtRoot) {
  const difference = {};
  const ownerBefore = manifest?.owner ?? null;
  const ownerAfter = builtRoot?.owner ?? null;
  if (ownerBefore !== ownerAfter)
    difference.owner = { manifest: ownerBefore, builtRoot: ownerAfter };
  for (const surface of ['api', 'mcp', 'cli']) {
    const left = new Set(surfaceAtoms(surface, manifest?.[surface]));
    const right = new Set(surfaceAtoms(surface, builtRoot?.[surface]));
    const manifestOnly = [...left].filter((atom) => !right.has(atom)).sort(byCodeUnit);
    const builtRootOnly = [...right].filter((atom) => !left.has(atom)).sort(byCodeUnit);
    if (manifestOnly.length || builtRootOnly.length)
      difference[surface] = { manifestOnly, builtRootOnly };
  }
  return difference;
}

/** What moved between a pinned difference and the current one, for the message. */
export function describeDifferenceMove(pinned, current) {
  const moves = [];
  if (canonicalJson(pinned?.owner) !== canonicalJson(current?.owner))
    moves.push(`owner ${canonicalJson(pinned?.owner)} -> ${canonicalJson(current?.owner)}`);
  for (const surface of ['api', 'mcp', 'cli'])
    for (const side of ['manifestOnly', 'builtRootOnly']) {
      const before = new Set(pinned?.[surface]?.[side] ?? []);
      const now = new Set(current?.[surface]?.[side] ?? []);
      const added = [...now].filter((atom) => !before.has(atom));
      const removed = [...before].filter((atom) => !now.has(atom));
      if (added.length) moves.push(`${surface} ${side} +[${added.join('; ')}]`);
      if (removed.length) moves.push(`${surface} ${side} -[${removed.join('; ')}]`);
    }
  return moves.length ? moves.join(', ') : 'the pinned entry has no difference recorded';
}

const sameSurfaces = (a, b) =>
  ['api', 'mcp', 'cli'].every(
    (surface) =>
      JSON.stringify(canonicalSurface(a[surface])) ===
      JSON.stringify(canonicalSurface(b[surface])),
  );

/**
 * Compute every package's snapshot. Returns
 * `{ ok, errors, warnings, files: { [packageName]: text } }`.
 *
 * Options: `root`; `corePath` (built core entry; default the tree's own);
 * `coreDist` (the built core's directory, for the route emitter's resolver
 * modules; default `corePath`'s directory);
 * `cliPath` (the `@happyvertical/smrt-cli/generator` build); `packages`
 * (names to write; all by default); `loaderParity` (also import each built
 * root and require equal inventories); `repin` (with `loaderParity`: rewrite
 * the pinned difference of listed ids that moved); `extraManifests` (tests only: extra
 * manifests to register for a package, to exercise the profile assertion).
 */
export async function collectServedSurface({
  root,
  corePath = path.join(root, 'packages/core/dist/index.js'),
  coreDist = path.dirname(corePath),
  cliPath = path.join(root, 'packages/cli/dist/generator.js'),
  packages: only,
  loaderParity = false,
  repin = false,
  extraManifests = {},
  concurrency = 4,
}) {
  const errors = [];
  const warnings = [];
  const packages = findPackages(root);

  // A package that builds and whose sources declare models must have a built
  // manifest (a missing build must fail, not pass). Packages with no `build`
  // script (test fixtures) publish no manifest and are not served.
  try {
    const modelPackages = new Set();
    for (const item of buildInventory(root).values())
      if (item.kind === 'model') modelPackages.add(item.name.split(':')[0]);
    const builds = new Set();
    const pkgRoot = path.join(root, 'packages');
    for (const dir of existsSync(pkgRoot) ? readdirSync(pkgRoot) : []) {
      const file = path.join(pkgRoot, dir, 'package.json');
      if (!existsSync(file)) continue;
      const json = JSON.parse(readFileSync(file, 'utf8'));
      if (json.scripts?.build) builds.add(json.name);
    }
    for (const name of [...modelPackages].sort(byCodeUnit))
      if (builds.has(name) && !packages.has(name))
        errors.push(`${name}: declares @smrt() models but has no built manifest; run pnpm build.`);
  } catch (error) {
    errors.push(`cannot read the model inventory: ${error.message}`);
  }

  // One qualified key, one manifest.
  const keyOwner = new Map();
  for (const pkg of packages.values()) {
    for (const key of Object.keys(pkg.manifest.objects ?? {})) {
      const prior = keyOwner.get(key);
      if (prior && prior !== pkg.packageName)
        errors.push(`duplicate qualified key ${key} in ${prior} and ${pkg.packageName}`);
      else keyOwner.set(key, pkg.packageName);
    }
  }
  if (!existsSync(corePath)) errors.push(`built core not found at ${corePath}; run pnpm build.`);
  if (!existsSync(cliPath)) errors.push(`built CLI generator not found at ${cliPath}; run pnpm build.`);
  if (errors.length > 0) return { ok: false, errors, warnings, files: {} };

  const names = [...packages.keys()].sort(byCodeUnit);
  const results = await mapLimit(names, concurrency, (packageName) => {
    const { order, missing } = dependencyClosure(packageName, packages);
    const pkg = packages.get(packageName);
    const parity =
      loaderParity && !NODE_ROOT_ALLOW.includes(packageName)
        ? path.join(pkg.dir, 'package.json')
        : undefined;
    return runWorker({
      packageName,
      corePath,
      coreDist,
      cliPath,
      manifests: order.map((name) => ({
        packageName: name,
        manifestPath: packages.get(name).manifestPath,
      })),
      extraManifests: extraManifests[packageName] ?? [],
      missing,
      parityPackageJson: parity,
    }).then((result) => ({ packageName, missing, ...result }));
  });

  const byName = new Map(results.map((r) => [r.packageName, r]));
  for (const result of results) errors.push(...(result.errors ?? []));

  // Loader parity against the reviewed list of known divergences, each
  // pinned to the reviewed difference between the two sides: a new
  // divergence fails, a listed one whose difference moved fails (or, with
  // `repin`, has its difference rewritten; ids are never added), a listed one
  // that no longer diverges fails (the fix deletes its entry), and so does an
  // entry for a key no parity run checks. The list file must exist.
  if (loaderParity) {
    const knownRel = `${SURFACE_DIR}/${PARITY_KNOWN_FILE}`;
    const knownFile = readParityKnownFile(root);
    if (!knownFile)
      errors.push(
        `loader parity: ${knownRel} is missing. It persists once created, as an empty list ({"divergences": {}}) when nothing diverges; restore it from git (git checkout -- ${knownRel}).`,
      );
    const known = knownFile?.divergences ?? {};
    const repinned = [];
    const checked = new Set();
    const diverging = new Set();
    for (const result of results) {
      if (!result.parityChecked) continue;
      for (const entry of result.entries ?? []) checked.add(entry.key);
      for (const entry of result.dependencyEntries ?? [])
        checked.add(`${entry.key} (under ${result.packageName})`);
      for (const divergence of result.parityDivergences ?? []) {
        checked.add(divergence.key);
        diverging.add(divergence.key);
        const entry = known[divergence.key];
        const difference = parityDifference(divergence.manifest, divergence.builtRoot);
        if (!entry) {
          errors.push(
            `loader parity: ${divergence.key} serves ${JSON.stringify(divergence.manifest)} from the manifest but ${JSON.stringify(divergence.builtRoot)} after importing ${result.packageName}'s built root. Fix the divergence; ${knownRel} only loses ids. Difference: ${canonicalJson(difference)}`,
          );
        } else if (canonicalJson(entry.difference) !== canonicalJson(difference)) {
          if (repin && knownFile) {
            entry.difference = difference;
            delete entry.expected;
            repinned.push(divergence.key);
          } else
            errors.push(
              `loader parity: ${divergence.key} diverges differently from its reviewed entry in ${knownRel}: ${describeDifferenceMove(entry.difference, difference)}. If the new difference is intended, re-pin it with pnpm check:served-surface --loader-parity --repin (it rewrites the difference of listed ids only, never adds one) and commit the file; the pull request shows the re-pin for review. Difference: ${canonicalJson(difference)}`,
            );
        }
      }
    }
    if (repinned.length > 0) {
      knownFile.raw.divergences = known;
      writeFileSync(
        path.join(root, SURFACE_DIR, PARITY_KNOWN_FILE),
        `${JSON.stringify(knownFile.raw, null, 2)}\n`,
      );
      warnings.push(`re-pinned in ${knownRel}: ${repinned.sort(byCodeUnit).join(', ')}`);
    }
    for (const key of Object.keys(known).sort(byCodeUnit)) {
      if (!checked.has(key))
        errors.push(
          `loader parity: ${SURFACE_DIR}/${PARITY_KNOWN_FILE} lists ${key}, which no loader-parity run checks (renamed, removed, or its package's root is not imported); delete the entry.`,
        );
      else if (!diverging.has(key))
        errors.push(
          `loader parity: ${key} no longer diverges; delete its entry from ${SURFACE_DIR}/${PARITY_KNOWN_FILE} (the list only shrinks).`,
        );
    }
  }
  // The closure must be complete: a dependency with no manifest would leave
  // ancestry, items and replacements out of every key it touches.
  for (const result of results)
    for (const name of result.missing ?? [])
      errors.push(
        `${result.packageName}: smrtDependency ${name} has no built manifest in this tree; the composition cannot be computed. Build it (pnpm build) or remove the dependency.`,
      );

  // Shadows: a dependency key that P's composition changes. Listed in P's
  // file when one of P's own classes serves it (a replacement), or when its
  // inventory under P differs from its inventory in the run of every other
  // package of P's closure that contains it (so a change a dependency already
  // makes is shown in that dependency's file, not repeated here). All runs
  // come from this same invocation, so files cannot go stale against each
  // other.
  const inventoryIn = (packageName, key) => {
    const run = byName.get(packageName);
    if (!run?.entries) return undefined;
    return (
      run.entries.find((e) => e.key === key) ??
      run.dependencyEntries?.find((e) => e.key === key)
    );
  };
  const replacedBy = new Map();
  const files = {};
  for (const name of names) {
    const result = byName.get(name);
    if (!result?.entries) continue;
    const ownKeys = new Set(result.entries.map((e) => e.key));
    const closure = dependencyClosure(name, packages).order.filter((n) => n !== name);
    const shadows = [];
    for (const dep of result.dependencyEntries ?? []) {
      const owner = dep.owner ?? dep.key;
      const replaced = ownKeys.has(owner);
      if (!replaced) {
        const elsewhere = closure
          .map((pkg) => inventoryIn(pkg, dep.key))
          .filter(Boolean);
        if (
          elsewhere.length === 0 ||
          elsewhere.some(
            (other) =>
              (other.owner ?? other.key) === owner && sameSurfaces(other, dep),
          )
        )
          continue;
      }
      shadows.push({ ...dep, owner });
      if (replaced && owner !== dep.key) {
        const list = replacedBy.get(dep.key) ?? [];
        list.push(name);
        replacedBy.set(dep.key, list);
      }
    }
    if (only && !only.includes(name)) continue;
    files[name] = serializePackage(name, {
      entries: result.entries,
      shadows,
      masked: result.masked ?? [],
      unmarked: result.unmarked ?? [],
      ambiguous: result.ambiguous ?? [],
    });
  }
  for (const [key, list] of replacedBy)
    if (list.length > 1)
      warnings.push(
        `${key} is replaced by ${list.sort(byCodeUnit).join(' and ')}; an app installing both fails at aggregation, and each file shows only its own composition.`,
      );
  return { ok: errors.length === 0, errors, warnings, files };
}

/**
 * The reviewed loader-parity list: `{ raw, divergences }`, or `null` when the
 * file is missing (an error wherever the list is read: it persists).
 */
export function readParityKnownFile(root) {
  const knownFile = path.join(root, SURFACE_DIR, PARITY_KNOWN_FILE);
  if (!existsSync(knownFile)) return null;
  const raw = JSON.parse(readFileSync(knownFile, 'utf8'));
  return { raw, divergences: raw.divergences ?? {} };
}

/** Whether `ref` names a commit in the repository at `root`. */
function gitRefResolves(root, ref) {
  try {
    execFileSync('git', ['rev-parse', '--verify', '--quiet', `${ref}^{commit}`], {
      cwd: root,
      stdio: 'ignore',
    });
    return true;
  } catch {
    return false;
  }
}

/**
 * The loader-parity list against a git ref (CI: the pull request's base).
 * Plain Node, no build. Fails when the file is missing, when the ref's file
 * cannot be read (only a successful tree lookup without it counts as
 * absent), and when the list holds an id the ref's list does not (ids only
 * leave). An id whose pinned difference changed since the ref passes but is
 * returned in `reviewItems`, which the entry prints as a required review
 * item. A ref without the file passes: the list is new there. Returns
 * `{ ok, errors, reviewItems }`.
 */
export function checkParityKnownAgainst({
  root,
  ref,
  readAtRef = requiredFileAtRef,
  refResolves = gitRefResolves,
}) {
  const errors = [];
  const reviewItems = [];
  const rel = `${SURFACE_DIR}/${PARITY_KNOWN_FILE}`;
  const current = readParityKnownFile(root);
  if (!current) {
    errors.push(
      `${rel} is missing. It persists once created, as an empty list ({"divergences": {}}) when nothing diverges; restore it from git.`,
    );
    return { ok: false, errors, reviewItems };
  }
  if (!refResolves(root, ref)) {
    errors.push(`cannot read git ref ${ref}; fetch it first (git fetch --no-tags --depth=1 origin <sha>).`);
    return { ok: false, errors, reviewItems };
  }
  let previousText;
  try {
    previousText = readAtRef(root, ref, rel);
  } catch (error) {
    errors.push(`cannot read ${rel} at ${ref}: ${String(error?.message ?? error).trim()}`);
    return { ok: false, errors, reviewItems };
  }
  // Absent only when the ref's tree was read and lacks the file.
  if (previousText === null) return { ok: true, errors, reviewItems };
  const previous = JSON.parse(previousText).divergences ?? {};
  for (const [key, entry] of Object.entries(current.divergences)) {
    if (!previous[key])
      errors.push(`${rel}: ${key} is not listed at ${ref}. Ids only leave the list: fix the divergence instead.`);
    else if (canonicalJson(previous[key].difference) !== canonicalJson(entry?.difference))
      reviewItems.push(
        `${key}: re-pinned since ${ref}: ${describeDifferenceMove(previous[key].difference, entry?.difference)}`,
      );
  }
  return { ok: errors.length === 0, errors, reviewItems };
}

/** Parse the entry flags; `--no-build` only under CI. */
export function planEntry(argv, env) {
  const againstFlag = argv.indexOf('--against');
  if (againstFlag !== -1) {
    const ref = argv[againstFlag + 1];
    return ref
      ? { against: ref }
      : { error: '--against needs a git ref.' };
  }
  const noBuild = argv.includes('--no-build');
  if (noBuild && env.CI !== 'true')
    return {
      error:
        '--no-build is only for CI=true, where the step runs right after pnpm run build in the same job. Locally the check builds first so the manifests match the sources.',
    };
  const repin = argv.includes('--repin');
  if (repin && !argv.includes('--loader-parity'))
    return { error: '--repin only applies with --loader-parity.' };
  return {
    build: !noBuild,
    write: argv.includes('--write'),
    loaderParity: argv.includes('--loader-parity'),
    repin,
  };
}

/**
 * Compute and compare with (or with `write`, rewrite) `served-surface/`.
 * Returns `{ ok, errors, warnings, changes, wrote }`.
 */
export async function runServedSurface(options) {
  const { root, write = false } = options;
  const result = await collectServedSurface(options);
  const changes = [];
  const wrote = [];
  if (!result.ok) return { ...result, changes, wrote };
  const dir = path.join(root, SURFACE_DIR);
  // One file per package: two packages whose names differ only in scope
  // would share a file, and one of them would never be compared.
  const expected = new Map();
  const clashes = [];
  for (const [name, text] of Object.entries(result.files)) {
    const file = surfaceFileName(name);
    const prior = expected.get(file);
    if (prior) clashes.push(`${SURFACE_DIR}/${file} would hold both ${prior.name} and ${name}; rename one package.`);
    else expected.set(file, { name, text });
  }
  if (clashes.length > 0) return { ...result, ok: false, errors: clashes, changes, wrote };
  const committed = existsSync(dir)
    ? readdirSync(dir).filter((file) => file.endsWith('.txt'))
    : [];
  if (write) {
    mkdirSync(dir, { recursive: true });
    for (const file of committed)
      if (!expected.has(file) && !options.packages) rmSync(path.join(dir, file));
    for (const [file, { text }] of expected) {
      const target = path.join(dir, file);
      if (!existsSync(target) || readFileSync(target, 'utf8') !== text) {
        writeFileSync(target, text);
        wrote.push(`${SURFACE_DIR}/${file}`);
      }
    }
    return { ...result, changes, wrote };
  }
  const errors = [];
  for (const [file, { name, text }] of expected) {
    const target = path.join(dir, file);
    const old = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
    if (old === text) continue;
    const found = classifyChanges(old, text);
    changes.push(...found.map((change) => ({ ...change, package: name })));
    if (found.length === 0) changes.push({ class: 'CHANGED', key: name, detail: 'formatting', package: name });
  }
  if (!options.packages)
    for (const file of committed)
      if (!expected.has(file))
        changes.push({ class: 'GONE', key: file, detail: 'package no longer has a built manifest', package: file });
  if (changes.length > 0) {
    errors.push(
      [
        'Served-surface changes:',
        ...changes.map((c) => `  ${c.class.padEnd(7)} ${c.key}: ${c.detail}`),
        'Review them, then run pnpm surface:served and commit served-surface/ with the change. Paste this block in the pull request description.',
      ].join('\n'),
    );
  }
  return { ...result, ok: errors.length === 0, errors, changes, wrote };
}

/** `turbo build`, the input-keyed freshness step the local entry runs first. */
export function buildFirst(root) {
  const run = spawnSync('pnpm', ['turbo', 'run', 'build'], {
    cwd: root,
    stdio: 'inherit',
  });
  return run.status === 0;
}
